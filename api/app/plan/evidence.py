"""지출 항목 → 감사 때 낼 증빙. 규칙표라 LLM이 지어내지 않는다.

근거: 중앙감특위 제출자료 목록(영수증철·계약서·지급 확인서), 재무 인수인계 메모("기프티콘은 구매 확인서 캡처",
"온라인 결제 때 포인트 적립 금지"), 24-1 감사 처분 사례(개인 현금영수증·포인트 적립, 개인카드 결제 후 이체).
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Evidence:
    kind: str
    words: tuple[str, ...]
    papers: tuple[str, ...]
    checklist: str | None = None  # 법령 점검표 주제 (web/src/lib/checklists.ts 의 id)


RULES: tuple[Evidence, ...] = (
    Evidence("상품권·기프티콘", ("기프티콘", "상품권", "모바일 쿠폰", "선물하기"),
             ("구매 확인서(캡처)", "받은 사람 명단(수령 확인)")),
    Evidence("상금·경품", ("상금", "경품", "상품"), ("지급 확인서", "받은 사람 서명"), "fee"),
    Evidence("사례금·수당", ("사례", "강사비", "강연료", "연사", "수당", "심판비", "멘토비", "인건비"),
             ("지급 확인서", "계좌이체 확인증", "원천징수 여부 확인"), "fee"),
    Evidence("대관·숙박", ("대관", "숙박", "펜션", "리조트", "장소"), ("계약서", "세금계산서 또는 카드 영수증")),
    Evidence("교통", ("버스", "대절", "교통", "택시"), ("계약서 또는 영수증", "탑승 인원 기록")),
    Evidence("주류", ("주류", "소주", "맥주", "막걸리", "와인"), ("영수증", "재원이 주류 구매를 허용하는지 확인"), "liquor"),
    # 파는 음식을 만드는 재료 — 조리·판매하는 사람은 건강진단(보건증) 대상 (식품위생법 제40조)
    Evidence("판매 음식 재료", ("식재료", "재료비", "조리", "먹거리"), ("카드 영수증", "조리·판매 인원 보건증 사본"), "liquor"),
    Evidence("상영·음원", ("상영", "음원", "저작권", "라이선스"), ("이용 허락서 또는 구매 영수증",), "copyright"),
    Evidence("식비·간식", ("식비", "간식", "음식", "다과", "도시락", "치킨", "피자", "음료"), ("카드 영수증",)),
    Evidence("인쇄·홍보", ("인쇄", "현수막", "포스터", "홍보", "제작"), ("카드 영수증", "결과물 사진")),
    Evidence("물품 구매", ("구매", "물품", "비품", "소모품", "용품"), ("카드 영수증 또는 거래명세서", "포인트·개인 적립 없이 결제")),
    Evidence("보험", ("보험",), ("보험증권",)),
)

COMMON = "공금 카드·계좌로 결제하고, 현금영수증은 기구 사업자(지출 증빙)로 받아요."


def papers_for(item: str) -> tuple[str, list[str], str | None]:
    """항목 이름으로 증빙 종류를 고른다. 맞는 규칙이 없으면 영수증만."""
    for rule in RULES:
        if any(w in item for w in rule.words):
            return rule.kind, list(rule.papers), rule.checklist
    return "기타", ["카드 영수증"], None
