/** 개인정보 수집·이용 동의 문구 (개인정보 보호법 제15조 제2항의 네 가지) */
export function consentText(c: ConsentInput): string {
  const org = c.org.trim() || "○○학생회";
  return [
    `[개인정보 수집·이용 동의]`,
    `${josa(org, "은", "는")} 아래와 같이 개인정보를 수집·이용합니다.`,
    `1. 목적: ${c.purpose.trim() || "○○ 행사 신청 확인과 안내"}`,
    `2. 항목: ${c.items.trim() || "이름, 학과, 연락처"}`,
    `3. 보관 기간: ${c.keep.trim() || "행사 종료 후 1개월까지 보관한 뒤 파기"}`,
    `4. 동의를 거부할 수 있으며, 거부하면 ${c.refuse.trim() || "행사 신청이 제한될 수 있습니다"}.`,
    `□ 위 내용에 동의합니다.`,
  ].join("\n");
}
